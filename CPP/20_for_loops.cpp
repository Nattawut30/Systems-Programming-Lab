#include <iostream>

int main()
{

    for (int i = 10; i >= 0; i--)
    {
        std::cout << i << std::endl;
    }

    std::cout << "HAPPY NEW YEAR!" << std::endl;

    // for loops are usually tend to be better in situation where you only need to repeat code a certain amount of time!

    return 0;
}